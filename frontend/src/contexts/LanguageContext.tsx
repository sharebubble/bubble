export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    // First choice: use language as stored in localStorage (if the user has selected one)
    const savedLang = localStorage.getItem('bubble-language');
    if (savedLang && LANGUAGES.includes(savedLang as Language)) {
      return savedLang as Language;
    }

    // Second choice: use the first available language from the user's browser / OS preferences
    for (const lang of navigator.languages) {
      // remove suffixes from languages like "de-AT"
      const baseLang = lang.split('-')[0];
      if (LANGUAGES.includes(baseLang as Language)) {
        return baseLang as Language;
      }
    }

    // Third choice: fallback to English
    return 'en';
  });

  const setLanguage = useCallback((lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('bubble-language', lang);
  }, []);

  const syncLanguage = useCallback((lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('bubble-language', lang);
  }, []);

  const t = useCallback(
    (key: string, params?: Record<string, string | number>): string => {
      let value = translations[language][key as keyof (typeof translations)['en']] || key;
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          value = value.replace(new RegExp(`{{${k}}}`, 'g'), String(v));
        }
      }
      return value;
    },
    [language],
  );

  const value = useMemo(
    () => ({ language, setLanguage, syncLanguage, t }),
    [language, setLanguage, syncLanguage, t],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
